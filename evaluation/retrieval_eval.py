def _filter(split: str | None) -> list[dict[str, Any]]:
    if not split or split == "all":
        return list(CASES)
    return [c for c in CASES if c.get("split") == split]


def _pk(memory_id: str) -> int:
    return abs(hash(memory_id)) % (2**62 - 1) + 1


class _DemoEmbedding:
    def __init__(self, dim: int = 32):
        self._dim = dim

    def health(self, deep: bool = False) -> dict:
        return {"provider": "demo", "status": "healthy", "dimension": self._dim}

    def encode(self, texts: list[str]) -> dict:
        return {
            "vectors": [[0.01 * ((hash(t) % 100) + j) for j in range(self._dim)] for t in texts],
            "dimension": self._dim,
            "model_name": "demo",
            "errors": None,
        }


def build_retriever(dim: int = 32) -> HybridRetriever:
    docs = []
    for m in CORPUS:
        mid = m["memory_id"]
        docs.append({
            "doc_id": mid,
            "text": m.get("content_text", ""),
            "content_text": m.get("content_text", ""),
            "user_id": m.get("user_id", ""),
            "memory_kind": m.get("memory_kind", "semantic"),
            "status": m.get("status", "active"),
            "memory_id": mid,
        })
    emb = _DemoEmbedding(dim=dim)
    vs = MemoryVectorStore(dim=dim)
    bm25 = BM25Retriever()
    bm25.index(docs)
    vs.upsert([{
        "vector_pk": _pk(d["memory_id"]),
        "vector": [0.01 * ((hash(d["content_text"]) % 100) + j) for j in range(dim)],
        "memory_id": d["memory_id"],
        "user_id": d["user_id"],
        "memory_kind": d["memory_kind"],
        "status": d["status"],
        "content_text": d["content_text"],
    } for d in docs])
    return HybridRetriever(emb, vs, bm25)


def _recall(ranked, gold, k):
    top = set(ranked[:k])
    return 1.0 if any(g in top for g in gold) else 0.0


def _mrr(ranked, gold):
    gset = set(gold)
    for i, mid in enumerate(ranked, 1):
        if mid in gset:
            return 1.0 / i
    return 0.0


def _pct(xs, p):
    if not xs:
        return 0.0
    s = sorted(xs)
    return float(s[min(len(s) - 1, max(0, int(round((p / 100.0) * (len(s) - 1)))))])


def run_retrieval_eval(*, split: str = "dev") -> dict[str, Any]:
    queries = _filter(split)
    hr = build_retriever()
    ks = [1, 3, 5, 10]
    recalls = {k: [] for k in ks}
    mrrs, lats = [], []
    for q in queries:
        resp = hr.search({"query": q["query"], "user_id": q.get("user_id"), "top_k": 10})
        ranked = [r["memory_id"] for r in resp.get("results", [])]
        gold = q.get("expected", {}).get("gold_memory_ids", [])
        for k in ks:
            recalls[k].append(_recall(ranked, gold, k))
        mrrs.append(_mrr(ranked, gold))
        lats.append(float(resp.get("meta", {}).get("elapsed_ms", 0.0)))
    n = max(len(queries), 1)
    return {
        "task": "retrieval",
        "split": split,
        "n": len(queries),
        "corpus_size": len(CORPUS),
        "recall_at_k": {str(k): sum(recalls[k]) / n for k in ks},
        "mrr": sum(mrrs) / n,
        "latency_ms": {"p50": _pct(lats, 50), "p95": _pct(lats, 95), "mean": sum(lats) / n},
        "backend": "HybridRetriever+BM25+MemoryVectorStore+DemoEmbedding",
    }


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--split", default="dev", choices=["dev", "held_out", "all"])
    args = p.parse_args()
    pprint(run_retrieval_eval(split=args.split))


if __name__ == "__main__":
    main()
